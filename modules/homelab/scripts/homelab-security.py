"""Bans and failed logins on the gateway (modules/homelab/fail2ban.nix).

Tunnel traffic reaches Caddy from 127.0.0.1, so fail2ban's iptables bans can't stop it. The
fail2ban action `homelab-ban` runs `ban`/`unban` here, which apply each ban in two places:
  - Caddy: every site block imports <state>/caddy/*.caddy, a client_ip matcher that answers 403
  - Cloudflare (when configured): an IP Access rule on the zone, so requests stop at the edge
State is one file per ban, <state>/jails/<jail>/<ip>; an IP stays blocked while any jail bans it.

  ban JAIL IP        fail2ban actionban
  unban JAIL IP      fail2ban actionunban
  reconcile          make Caddy and Cloudflare match fail2ban's current bans (timer)
  notify JAIL IP BANTIME FAILURES   ntfy message for a new ban (fail2ban action homelab-ntfy)
  report             write security.json for the dashboard (timer, and after bans/unbans)
  unban-request JAIL:IP   unban from the dashboard (homelab-unban@.service)

Settings come from the JSON file given with --config (generated by fail2ban.nix).
"""

import argparse
import ast
import fcntl
import grp
import hashlib
import ipaddress
import json
import os
import re
import sqlite3
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone

CF_API = "https://api.cloudflare.com/client/v4"
CF_NOTE = "homelab-ban (fail2ban)"
JAIL_RE = re.compile(r"^[A-Za-z0-9_.-]{1,64}$")
IP_CHARS = r"[0-9A-Fa-f:.]+"

# Failed logins in Vaultwarden's log (src/api/identity.rs, two_factor/*.rs, admin.rs) and sshd's.
# kind: what failed. A 2FA failure means the password was right.
PATTERNS = [
    ("password", re.compile(
        r"Username or (?:password|access code) is incorrect\. Try again\. "
        rf"IP: (?P<ip>{IP_CHARS})\. Username: (?P<user>.*)\.$")),
    ("api key", re.compile(
        rf"Incorrect client_secret\. IP: (?P<ip>{IP_CHARS})\. "
        r"Username: (?P<user>.*)\.$")),
    ("2fa", re.compile(
        rf"Invalid TOTP code! Server time: .* IP: (?P<ip>{IP_CHARS})$")),
    ("admin", re.compile(rf"Invalid admin token\. IP: (?P<ip>{IP_CHARS})")),
    ("admin", re.compile(
        rf"Invalid or expired admin JWT\. IP: (?P<ip>{IP_CHARS})\.")),
    ("ssh", re.compile(
        r"(?:Failed \S+|Invalid user) (?:for )?(?:invalid user )?"
        rf"(?P<user>\S+) from (?P<ip>{IP_CHARS})")),
]


def parse_failure(message):
    """(kind, ip, user) for a failed-login log line, else None."""
    message = message.rstrip()
    for kind, pattern in PATTERNS:
        m = pattern.search(message)
        if m:
            ip = normalize_ip(m.group("ip").rstrip("."))
            if ip:
                user = m.groupdict().get("user")
                return kind, ip, (user or None)
    return None


def normalize_ip(value):
    try:
        return str(ipaddress.ip_address(value.strip()))
    except ValueError:
        return None


def ip_sort_key(ip):
    addr = ipaddress.ip_address(ip)
    return addr.version, addr


def check_jail(jail):
    if not JAIL_RE.match(jail):
        sys.exit(f"invalid jail name: {jail!r}")
    return jail


def check_ip(value):
    ip = normalize_ip(value)
    if ip is None:
        sys.exit(f"invalid IP address: {value!r}")
    return ip


def iso(ts):
    if ts is None:
        return None
    return datetime.fromtimestamp(ts, timezone.utc).isoformat()


def run(cmd, check=True):
    return subprocess.run(cmd, check=check, capture_output=True, text=True)


def write_atomic(path, text, mode=0o644, group=None):
    """Write text to path via a temporary file; returns True when it changed."""
    try:
        with open(path) as f:
            if f.read() == text:
                return False
    except FileNotFoundError:
        pass
    tmp = f"{path}.tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.chmod(tmp, mode)
    if group:
        os.chown(tmp, -1, grp.getgrnam(group).gr_gid)
    os.replace(tmp, path)
    return True


def cloudflare_configured(cfg):
    return bool(cfg.get("cloudflareZone")
                and os.path.exists(cfg.get("cloudflareTokenFile") or ""))


class Bans:
    """The ban state shared by Caddy and Cloudflare (<state>/jails/<jail>/<ip>)."""

    def __init__(self, cfg):
        self.cfg = cfg
        self.jails_dir = os.path.join(cfg["stateDir"], "jails")
        self.caddy_file = os.path.join(cfg["stateDir"], "caddy", "bans.caddy")
        os.makedirs(self.jails_dir, mode=0o700, exist_ok=True)
        self.lock = open(os.path.join(cfg["stateDir"], ".lock"), "w")
        fcntl.flock(self.lock, fcntl.LOCK_EX)

    def held(self):
        """{ip: {jail, ...}} for every applied ban."""
        out = {}
        for jail in sorted(os.listdir(self.jails_dir)):
            for name in os.listdir(os.path.join(self.jails_dir, jail)):
                ip = normalize_ip(name)
                if ip:
                    out.setdefault(ip, set()).add(jail)
        return out

    def add(self, jail, ip):
        """Caddy first: it works without Cloudflare, and a Cloudflare error raises."""
        new = ip not in self.held()
        os.makedirs(os.path.join(self.jails_dir, jail), mode=0o700,
                    exist_ok=True)
        with open(os.path.join(self.jails_dir, jail, ip), "w") as f:
            f.write(f"{int(time.time())}\n")
        self.render()
        if new:
            self.cloudflare_block(ip)

    def remove(self, jail, ip):
        try:
            os.unlink(os.path.join(self.jails_dir, jail, ip))
        except FileNotFoundError:
            pass
        self.render()
        if ip not in self.held():
            self.cloudflare_unblock(ip)

    def render(self):
        """Caddy snippet: 403 for every banned IP; no file at all when none.

        Caddy is reloaded when the snippet differs from the one last handed to it, so a reload
        that couldn't be queued is retried on the next ban, unban or reconcile."""
        ips = sorted(self.held(), key=ip_sort_key)
        os.makedirs(os.path.dirname(self.caddy_file), mode=0o755,
                    exist_ok=True)
        text = ""
        if ips:
            text = (
                "# Generated by homelab-security (fail2ban bans). "
                "Do not edit.\n"
                f"@hl_banned client_ip {' '.join(ips)}\n"
                'respond @hl_banned "Forbidden" 403\n'
            )
            write_atomic(self.caddy_file, text)
        elif os.path.exists(self.caddy_file):
            os.unlink(self.caddy_file)

        applied_file = os.path.join(self.cfg["stateDir"], "caddy-applied")
        digest = hashlib.sha256(text.encode()).hexdigest()
        try:
            with open(applied_file) as f:
                applied = f.read().strip()
        except FileNotFoundError:
            applied = None
        if applied == digest:
            return
        # Several bans at once (fail2ban restoring them) merge into one queued reload
        res = run(["systemctl", "try-reload-or-restart", "--no-block",
                   self.cfg["caddyUnit"]], check=False)
        if res.returncode == 0:
            write_atomic(applied_file, digest + "\n", mode=0o600)
            print(f"caddy: {len(ips)} banned address(es)")
        else:
            print(f"caddy: reload failed, retrying next time: {res.stderr.strip()}",
                  file=sys.stderr)

    # Cloudflare IP Access rules (zone level)

    def cf_enabled(self):
        return cloudflare_configured(self.cfg)

    def cf(self, method, path, body=None, query=None):
        with open(self.cfg["cloudflareTokenFile"]) as f:
            token = f.read().strip()
        api = self.cfg.get("cloudflareApi") or CF_API
        url = f"{api}/zones/{self.cfg['cloudflareZone']}{path}"
        if query:
            url += "?" + urllib.parse.urlencode(query)
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(url, data=data, method=method, headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        })
        try:
            with urllib.request.urlopen(req, timeout=20) as resp:
                return json.load(resp)
        except urllib.error.HTTPError as e:
            try:
                return json.load(e)
            except ValueError:
                return {"success": False,
                        "errors": [{"code": e.code, "message": str(e)}]}

    def cf_rules(self, ip=None):
        rules, page = [], 1
        while True:
            query = {"mode": "block", "notes": CF_NOTE, "per_page": 100,
                     "page": page}
            if ip:
                query["configuration.value"] = ip
            res = self.cf("GET", "/firewall/access_rules/rules", query=query)
            if not res.get("success"):
                raise RuntimeError(f"cloudflare: list failed: {res.get('errors')}")
            # notes is a substring filter: keep only rules this tool made
            rules += [r for r in res["result"] if r.get("notes") == CF_NOTE]
            info = res.get("result_info") or {}
            if page >= info.get("total_pages", 1):
                return rules
            page += 1

    def cloudflare_block(self, ip):
        if not self.cf_enabled():
            return
        target = "ip6" if ipaddress.ip_address(ip).version == 6 else "ip"
        res = self.cf("POST", "/firewall/access_rules/rules", body={
            "mode": "block",
            "configuration": {"target": target, "value": ip},
            "notes": CF_NOTE,
        })
        codes = {e.get("code") for e in res.get("errors") or []}
        if res.get("success") or 10009 in codes:  # 10009: rule already exists
            print(f"cloudflare: blocked {ip}")
        else:
            raise RuntimeError(f"cloudflare: blocking {ip} failed: "
                               f"{res.get('errors')}")

    def cloudflare_unblock(self, ip):
        if not self.cf_enabled():
            return
        for rule in self.cf_rules(ip):
            if rule["configuration"]["value"] != ip:
                continue
            res = self.cf("DELETE", f"/firewall/access_rules/rules/{rule['id']}")
            if not res.get("success"):
                raise RuntimeError(f"cloudflare: unblocking {ip} failed: "
                                   f"{res.get('errors')}")
            print(f"cloudflare: unblocked {ip}")


def fail2ban_banned(cfg):
    """{jail: {ip, ...}} from the running fail2ban, or None when it isn't running."""
    res = run([cfg["fail2banClient"], "banned"], check=False)
    if res.returncode != 0:
        return None
    out = {}
    for entry in ast.literal_eval(res.stdout.strip() or "[]"):
        for jail, ips in entry.items():
            out[jail] = {ip for ip in map(normalize_ip, ips) if ip}
    return out


def cmd_ban(cfg, args):
    Bans(cfg).add(check_jail(args.jail), check_ip(args.ip))
    refresh_report(cfg)


def cmd_unban(cfg, args):
    Bans(cfg).remove(check_jail(args.jail), check_ip(args.ip))
    refresh_report(cfg)


def cmd_reconcile(cfg, args):
    """Make the applied bans match fail2ban's. Covers bans that expired while fail2ban was
    stopped (its flush is a no-op for this action, so a restart keeps the edge bans in place),
    and Cloudflare rules removed or added by hand."""
    banned = fail2ban_banned(cfg)
    if banned is None:
        print("fail2ban is not running; leaving bans as they are")
        return
    bans = Bans(cfg)
    want = {}
    for jail in cfg["banJails"]:
        for ip in banned.get(jail, ()):
            want.setdefault(ip, set()).add(jail)
    have = bans.held()
    for ip, jails in have.items():
        for jail in jails - want.get(ip, set()):
            print(f"reconcile: {ip} is no longer banned in {jail}")
            os.unlink(os.path.join(bans.jails_dir, jail, ip))
    for ip, jails in want.items():
        for jail in jails - have.get(ip, set()):
            print(f"reconcile: {ip} is banned in {jail}")
            os.makedirs(os.path.join(bans.jails_dir, jail), mode=0o700,
                        exist_ok=True)
            with open(os.path.join(bans.jails_dir, jail, ip), "w") as f:
                f.write(f"{int(time.time())}\n")
    bans.render()
    if bans.cf_enabled():
        rules = {r["configuration"]["value"]: r for r in bans.cf_rules()}
        for ip in set(want) - set(rules):
            bans.cloudflare_block(ip)
        for ip in set(rules) - set(want):
            bans.cloudflare_unblock(ip)


def journal_failures(cfg, since="-24h"):
    """Failed logins from the watched units' journals, oldest first."""
    out = []
    for unit in cfg["journalUnits"]:
        res = run(["journalctl", "-u", unit, f"--since={since}", "-o", "json",
                   "--no-pager", "--output-fields=MESSAGE"], check=False)
        for line in res.stdout.splitlines():
            try:
                entry = json.loads(line)
            except ValueError:
                continue
            message = entry.get("MESSAGE")
            if isinstance(message, list):  # non-UTF-8: journald sends bytes
                message = bytes(message).decode("utf-8", "replace")
            if not isinstance(message, str):
                continue
            parsed = parse_failure(message)
            if parsed:
                kind, ip, user = parsed
                ts = int(entry.get("__REALTIME_TIMESTAMP", 0)) / 1e6
                out.append({"time": ts, "ip": ip, "user": user, "kind": kind,
                            "unit": unit})
    out.sort(key=lambda a: a["time"])
    return out


def fail2ban_history(cfg, since, extra_ips):
    """Ban rows from fail2ban's database: recent ones plus the latest for extra_ips."""
    path = cfg["fail2banDb"]
    if not os.path.exists(path):
        return []
    db = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=10)
    try:
        rows = db.execute(
            "SELECT jail, ip, timeofban, bantime, bancount, data FROM bans "
            "WHERE timeofban >= ? ORDER BY timeofban DESC", (since,)).fetchall()
        for jail, ip in extra_ips:
            rows += db.execute(
                "SELECT jail, ip, timeofban, bantime, bancount, data FROM bans "
                "WHERE jail = ? AND ip = ? ORDER BY timeofban DESC LIMIT 1",
                (jail, ip)).fetchall()
    finally:
        db.close()
    return rows


def ban_details(data):
    """(users, kinds, failures) from a ban row's data (the log lines that led to it)."""
    users, kinds = [], []
    try:
        data = json.loads(data) if data else {}
    except ValueError:
        data = {}
    for match in data.get("matches") or []:
        if isinstance(match, list):  # fail2ban may store a line as its parts
            match = "".join(str(m) for m in match)
        parsed = parse_failure(str(match))
        if parsed:
            kind, _, user = parsed
            if kind not in kinds:
                kinds.append(kind)
            if user and user not in users:
                users.append(user)
    return users, kinds, data.get("failures")


def build_report(cfg):
    now = time.time()
    banned = fail2ban_banned(cfg)
    active = {(j, ip) for j, ips in (banned or {}).items() for ip in ips}
    attempts = journal_failures(cfg)
    by_ip = {}
    for a in attempts:
        by_ip.setdefault(a["ip"], []).append(a)

    bans, seen = [], set()
    rows = fail2ban_history(cfg, now - cfg["historyDays"] * 86400, active)
    for jail, ip, timeofban, bantime, bancount, data in rows:
        ip = normalize_ip(ip or "")
        if not ip or (jail, ip) in seen:
            continue
        seen.add((jail, ip))
        users, kinds, failures = ban_details(data)
        for a in by_ip.get(ip, []):
            if a["user"] and a["user"] not in users:
                users.append(a["user"])
        bans.append({
            "jail": jail,
            "ip": ip,
            "active": (jail, ip) in active,
            "bannedAt": iso(timeofban),
            "expiresAt": iso(timeofban + bantime) if bantime >= 0 else None,
            "banCount": bancount,
            "failures": failures,
            "users": users,
            "kinds": kinds,
        })
    for h in read_history(cfg, now - cfg["historyDays"] * 86400):
        if (h["jail"], h["ip"]) in active:
            continue
        bt, bc = h.get("bannedAt"), h.get("bantime")
        bans.append({
            "jail": h["jail"],
            "ip": h["ip"],
            "active": False,
            "bannedAt": iso(bt),
            "expiresAt": iso(bt + bc) if bt and bc is not None and bc >= 0 else None,
            "unbannedAt": iso(h["unbannedAt"]),
            "banCount": h.get("banCount"),
            "failures": h.get("failures"),
            "users": h.get("users") or [],
            "kinds": h.get("kinds") or [],
        })
    # Banned now but missing from the database (e.g. banned by hand)
    for jail, ip in sorted(active - seen):
        bans.append({"jail": jail, "ip": ip, "active": True, "bannedAt": None,
                     "expiresAt": None, "banCount": None, "failures": None,
                     "users": [], "kinds": []})
    # Active bans first, newest first within each
    bans.sort(key=lambda b: b["bannedAt"] or "", reverse=True)
    bans.sort(key=lambda b: not b["active"])

    banned_ips = {ip for _, ip in active}
    trusted = [ipaddress.ip_network(n, strict=False) for n in cfg.get("ignoreIP", [])]
    recent = [{
        "time": iso(a["time"]), "ip": a["ip"], "user": a["user"],
        "kind": a["kind"], "banned": a["ip"] in banned_ips,
        # fail2ban's ignoreip (homelab link, tailnet): never banned
        "trusted": any(ipaddress.ip_address(a["ip"]) in n for n in trusted),
    } for a in reversed(attempts)][:200]

    active_bans = [b for b in bans if b["active"]]
    last_ban = max((b["bannedAt"] for b in bans if b["bannedAt"]), default=None)
    if last_ban:
        age = now - datetime.fromisoformat(last_ban).timestamp()
        last_ban_text = (f"{int(age // 60)}m ago" if age < 3600
                         else f"{int(age // 3600)}h ago" if age < 172800
                         else f"{int(age // 86400)}d ago")
    else:
        last_ban_text = "none in 7d"
    if banned is None:
        status = "fail2ban not running"
    elif active_bans:
        status = f"{len(active_bans)} banned"
    else:
        status = "ok"
    return {
        "generated": iso(now),
        "fail2ban": banned is not None,
        "edge": "cloudflare + caddy" if cloudflare_configured(cfg) else "caddy",
        "summary": {
            "status": status,
            "activeBans": len(active_bans),
            "attempts24h": len(attempts),
            "lastBan": last_ban,
            "lastBanText": last_ban_text,  # for the tile (a null date renders as 1970)
        },
        "jails": sorted(banned or {}),
        "bans": bans,
        "attempts": recent,
    }


def cmd_report(cfg, args):
    report = build_report(cfg)
    try:
        with open(cfg["reportFile"]) as f:
            before = json.load(f).get("summary", {})
    except (OSError, ValueError):
        before = {}
    os.makedirs(os.path.dirname(cfg["reportFile"]), exist_ok=True)
    write_atomic(cfg["reportFile"], json.dumps(report, indent=1) + "\n",
                 mode=0o640, group=cfg.get("reportGroup"))
    s = report["summary"]
    # Runs every minute: only log changes
    if (before.get("status"), before.get("attempts24h")) != (s["status"], s["attempts24h"]):
        print(f"{s['status']}; {s['attempts24h']} failed logins in 24h")


def refresh_report(cfg):
    run(["systemctl", "start", "--no-block", cfg["reportUnit"]], check=False)


def cmd_notify(cfg, args):
    """ntfy message for a new ban, naming the accounts that were tried."""
    jail, ip = check_jail(args.jail), check_ip(args.ip)
    tried = [a for a in journal_failures(cfg, since="-2d") if a["ip"] == ip]
    users = sorted({a["user"] for a in tried if a["user"]})
    kinds = {a["kind"] for a in tried}
    try:
        seconds = int(args.bantime)
        if seconds < 0:
            length = "good"
        elif seconds >= 86400:
            days = round(seconds / 86400, 1)
            length = f"{days:g} day{'s' if days != 1 else ''}"
        else:
            length = f"{max(1, seconds // 3600)} h"
    except ValueError:
        length = args.bantime
    who = f" as {', '.join(users)}" if users else ""
    if "2fa" in kinds:
        title = f"{jail}: wrong 2FA code from {ip}"
        priority = "urgent"
        body = (f"{ip} entered a correct master password but failed 2FA. "
                f"Banned for {length}. If this wasn't you, change your master "
                "password now.")
    else:
        title = f"{jail}: banned {ip}"
        priority = "high"
        body = (f"{args.failures} failed logins{who}. Banned for {length}. "
                "Your own mistake? Unban it from the dashboard.")
    headers = {
        "Title": title,
        "Priority": priority,
        "Tags": "rotating_light,shield",
        "Click": cfg["dashboardUrl"],
        "Actions": f"view, Review bans, {cfg['dashboardUrl']}",
    }
    with open(cfg["ntfyHeaderFile"]) as f:
        for line in f:
            if ":" in line:
                k, v = line.split(":", 1)
                headers[k.strip()] = v.strip()
    req = urllib.request.Request(cfg["ntfyUrl"], data=body.encode(),
                                 headers=headers, method="POST")
    with urllib.request.urlopen(req, timeout=15):
        pass


def history_file(cfg):
    return os.path.join(cfg["stateDir"], "unbanned.jsonl")


def read_history(cfg, since):
    """Bans unbanned from the dashboard (fail2ban deletes those from its database)."""
    out = []
    try:
        with open(history_file(cfg)) as f:
            for line in f:
                try:
                    entry = json.loads(line)
                except ValueError:
                    continue
                if entry.get("unbannedAt", 0) >= since:
                    out.append(entry)
    except FileNotFoundError:
        pass
    return out


def cmd_unban_request(cfg, args):
    """Unban from the dashboard: homelab-unban@<jail>:<ip>.service runs this as root."""
    jail, _, ip = args.instance.partition(":")
    jail, ip = check_jail(jail), check_ip(ip)
    banned = fail2ban_banned(cfg)
    if banned is None:
        sys.exit("fail2ban is not running")
    if jail not in banned:
        sys.exit(f"no jail named {jail}")
    if ip not in banned[jail]:
        print(f"{ip} is not banned in {jail}")
    else:
        rows = fail2ban_history(cfg, time.time(), [(jail, ip)])
        entry = {"jail": jail, "ip": ip, "unbannedAt": time.time()}
        if rows:
            _, _, timeofban, bantime, bancount, data = rows[0]
            users, kinds, failures = ban_details(data)
            entry.update(bannedAt=timeofban, bantime=bantime, banCount=bancount,
                         users=users, kinds=kinds, failures=failures)
        run([cfg["fail2banClient"], "set", jail, "unbanip", ip])
        path = history_file(cfg)
        try:
            with open(path) as f:
                lines = f.readlines()[-199:]
        except FileNotFoundError:
            lines = []
        lines.append(json.dumps(entry) + "\n")
        write_atomic(path, "".join(lines), mode=0o600)
        print(f"unbanned {ip} from {jail}")
    cmd_report(cfg, args)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--config", required=True)
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("ban", "unban"):
        s = sub.add_parser(name)
        s.add_argument("jail")
        s.add_argument("ip")
    sub.add_parser("reconcile")
    sub.add_parser("report")
    s = sub.add_parser("notify")
    for a in ("jail", "ip", "bantime", "failures"):
        s.add_argument(a)
    s = sub.add_parser("unban-request")
    s.add_argument("instance", help="JAIL:IP")
    args = p.parse_args()
    with open(args.config) as f:
        cfg = json.load(f)
